#!/usr/bin/env node
// Regenerate web/icons.js with just the game-icons.net icons (CC BY 3.0) the
// site uses: every talent icon the rules in web/meta.js pick for the current
// game data, plus the class, race, scenario and interface icons.
//
//   npm install @iconify-json/game-icons
//   fsim api '{"op":"catalog"}' > catalog.json
//   node tools/build_icons.mjs node_modules/@iconify-json/game-icons/icons.json catalog.json
//
// The GitHub Pages workflow runs this on every deploy, so icons for new
// talents in a patch appear without anyone editing this file.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const [iconsPath, catalogPath] = process.argv.slice(2);
if (!iconsPath || !catalogPath) {
  console.error('usage: build_icons.mjs <game-icons icons.json> <catalog.json>');
  process.exit(2);
}
const set = JSON.parse(readFileSync(iconsPath, 'utf8'));
const catalog = JSON.parse(readFileSync(catalogPath, 'utf8'));
const M = await import(join(root, 'web', 'meta.js'));

const want = new Set(['rune-stone']);
const add = (n) => { if (n) want.add(n); };
Object.values(M.CLASS_ICONS).forEach(add);
Object.values(M.RACE_ICONS).forEach(add);
M.SCENARIOS.forEach((s) => add(s.icon));
Object.values(M.TREE_STYLE).flat().forEach(([, icon]) => add(icon));
catalog.gear.forEach((g) => add(M.gearIcon(g.id)));
// Same order as prepareClass() in web/talents.js, so the rotation of
// alternative icons matches what the page draws.
for (const c of catalog.classes) {
  const used = Object.fromEntries(c.trees.map((t) => [t, {}]));
  for (const t of c.talents) add(M.talentIcon(c.id, t, used[t.tree]).icon);
}
// Interface icons named in the page's scripts.
for (const f of readdirSync(join(root, 'web')).filter((f) => f.endsWith('.js') && f !== 'icons.js' && f !== 'meta.js')) {
  for (const m of readFileSync(join(root, 'web', f), 'utf8').matchAll(/'([a-z0-9]+(?:-[a-z0-9]+)*)'/g)) {
    if (set.icons[m[1]]) add(m[1]);
  }
}

const missing = [...want].filter((n) => !set.icons[n]);
if (missing.length) {
  console.error(`unknown icon names: ${missing.join(', ')}`);
  process.exit(1);
}
const lines = [
  '// Generated by tools/build_icons.mjs from game-icons.net (CC BY 3.0:',
  '// Lorc, Delapouite and contributors). Do not edit by hand.',
  `// ${want.size} icons, each the path data of a ${set.width || 512}x${set.height || 512} SVG.`,
  'export const ICONS = {',
];
for (const n of [...want].sort()) {
  const body = set.icons[n].body;
  const paths = [...body.matchAll(/<path[^>]* d="([^"]+)"/g)].map((m) => m[1]);
  if (!paths.length) throw new Error(`${n}: no path data`);
  lines.push(`  '${n}': ${JSON.stringify(paths.join(' '))},`);
}
lines.push('};', '');
writeFileSync(join(root, 'web', 'icons.js'), lines.join('\n'));
console.log(`wrote ${want.size} icons to web/icons.js`);
